#!/usr/bin/env python3
"""Validate the editable family catalogue and generate the offline browser data."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    data = json.loads((ROOT / "data/family.json").read_text(encoding="utf-8"))
    people = data["people"]
    keys = [p["key"] for p in people]
    ids = [p["id"] for p in people]
    if len(set(keys)) != len(keys) or len(set(ids)) != len(ids):
        raise ValueError("Person keys and IDs must be unique")
    if keys.count("root") != 1:
        raise ValueError("Exactly one person must have key 'root'")
    if any(p["branch"] not in ("self", "m", "f") for p in people):
        raise ValueError("Unknown person branch")
    if len({e["id"] for e in data["edges"]}) != len(data["edges"]):
        raise ValueError("Relationship IDs must be unique")
    parents = {key: [] for key in keys}
    for edge in data["edges"]:
        if edge["a"] not in parents or edge["b"] not in parents or edge["a"] == edge["b"]:
            raise ValueError("Invalid relationship endpoints")
        if edge["type"] not in ("parent", "spouse", "sibling", "stepparent"):
            raise ValueError("Unknown relationship type")
        if edge["type"] == "parent":
            parents[edge["b"]].append(edge["a"])
    visited, visiting = set(), set()

    def visit(key):
        if key in visiting:
            raise ValueError("Parent relationships contain a cycle")
        if key in visited:
            return
        visiting.add(key)
        for parent in parents[key]:
            visit(parent)
        visiting.remove(key)
        visited.add(key)

    for key in keys:
        visit(key)
    sources = data["sources"]
    if len({s["id"] for s in sources}) != len(sources):
        raise ValueError("Source IDs must be unique")
    for entry in people + data["edges"]:
        for index in entry.get("refs", []):
            if type(index) is not int or not 0 <= index < len(sources):
                raise ValueError("Invalid source reference")
    for group in data.get("lineages", []):
        if any(key not in parents for key in group["anchors"]):
            raise ValueError("Unknown lineage anchor")
    geography = data.get("geography", {"places": [], "events": []})
    place_ids = {place["id"] for place in geography["places"]}
    for event in geography["events"]:
        if event["personId"] not in ids or event["placeId"] not in place_ids:
            raise ValueError("Invalid map event")
    payload = json.dumps(data, ensure_ascii=False, indent=2)
    (ROOT / "app/tree-data.js").write_text(
        "// Generated by scripts/build.py from data/family.json.\nwindow.FAMILY_TREE = "
        + payload + ";\n", encoding="utf-8")
    print(f"Built {len(people)} people and {len(data['edges'])} relationships")


if __name__ == "__main__":
    build()
